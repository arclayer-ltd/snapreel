#!/usr/bin/env python3
"""Pieces of the app's real screens, lifted out to float beside the site's iPhones (like UI cards pulled out of
a phone's screen): a library row, the Notes / Transcript / Comments tabs, the "Save to Photos" buttons, the
"Saved on this iPhone" note. Cut from the same CI screenshots as the phones (art/web/screens/{light,dark}), so
they are exactly the app's, in Light and Dark.

Run from the repo root:

    python scripts/web-lifts.py

Outputs: web/public/marketing/lifts/{name}-{light|dark}.webp (2x, transparent rounded corners) and
web/components/marketing/lifts-manifest.ts (each piece's size in points).
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "art/web/screens"
OUT = ROOT / "web/public/marketing/lifts"
MANIFEST = ROOT / "web/components/marketing/lifts-manifest.ts"

# name: (screenshot, rough box in pt (x0, y0, x1, y1) around the piece, corner radius in pt or "pill",
#        pad: points of the screen's background kept around a piece that has no card of its own)
PIECES: dict[str, tuple[str, tuple[int, int, int, int], float | str, int]] = {
    "row-feedback": ("lib.videos", (14, 470, 361, 579), 14, 0),
    "row-checkout": ("lib.videos", (14, 357, 361, 466), 14, 0),
    "actions": ("share.link.player", (12, 511, 364, 586), 18, 7),
    "tabs": ("share.link.comments", (10, 378, 326, 425), "pill", 0),
    "saved": ("flow.voice", (100, 570, 280, 600), "pill", 10),
}


def trim(a: np.ndarray, bg: np.ndarray) -> tuple[int, int, int, int]:
    away = np.abs(a.astype(int) - bg.astype(int)).max(-1) > 5
    ys, xs = np.where(away)
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    sizes: dict[str, dict[str, float]] = {}
    for name, (shot, (x0, y0, x1, y1), radius, pad) in PIECES.items():
        for mode in ("light", "dark"):
            img = np.asarray(Image.open(SRC / mode / f"{shot}.png").convert("RGB"))
            box = img[y0 * 3 : y1 * 3, x0 * 3 : x1 * 3]
            bg = box[1, 1]
            l, t, r, b = trim(box, bg)
            p = pad * 3
            l, t, r, b = max(0, l - p), max(0, t - p), min(box.shape[1], r + p), min(box.shape[0], b + p)
            piece = Image.fromarray(box[t:b, l:r]).convert("RGBA")
            w, h = piece.size
            rad = h / 2 if radius == "pill" else float(radius) * 3
            if rad:
                k = 4  # draw the mask big, then shrink it, for smooth edges
                mask = Image.new("L", (w * k, h * k), 0)
                ImageDraw.Draw(mask).rounded_rectangle((0, 0, w * k - 1, h * k - 1), radius=rad * k, fill=255)
                piece.putalpha(mask.resize((w, h), Image.LANCZOS))
            out = piece.resize((round(w * 2 / 3), round(h * 2 / 3)), Image.LANCZOS)
            out.save(OUT / f"{name}-{mode}.webp", quality=90, method=6)
            if mode == "light":
                sizes[name] = {"w": round(w / 3, 1), "h": round(h / 3, 1)}
            print(f"{name} {mode} {out.size}")
    lines = [
        "/* Generated by scripts/web-lifts.py: pieces of the app's screens, in points. Don't edit by hand. */",
        "",
        f"export const lifts = {json.dumps(sizes)} as const;",
        "",
        "export type LiftName = keyof typeof lifts;",
        "",
    ]
    MANIFEST.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
